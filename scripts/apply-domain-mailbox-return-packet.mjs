#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

function parseArgs(argv) {
  const values = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (!arg.startsWith("--")) continue;
    const key = arg.slice(2);
    const next = argv[index + 1];
    if (!next || next.startsWith("--")) {
      values[key] = "true";
    } else {
      values[key] = next;
      index += 1;
    }
  }
  return values;
}

function readInput(file) {
  if (file) return fs.readFileSync(file, "utf8");
  return fs.readFileSync(0, "utf8");
}

function requireMatch(label, text, pattern) {
  const match = text.match(pattern);
  if (!match?.[1]) {
    throw new Error(`Missing ${label} in domain and mailbox return packet.`);
  }
  return match[1].trim();
}

function validDomain(value) {
  return /^[a-z0-9.-]+\.[a-z]{2,}$/i.test(value);
}

function validEmail(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);
}

function validMailProvider(value) {
  return ["zoho", "google", "spacemail"].includes(value);
}

function assertValid(label, value, test) {
  if (!test(value)) throw new Error(`Invalid ${label}: ${value}`);
}

function writeApprovalStatus(values) {
  const file = path.join(process.cwd(), "ops/founder-approval-status.json");
  const existing = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : {};
  const status = {
    generatedFor: "MCPScan first revenue launch",
    ...existing,
    updatedAt: new Date().toISOString(),
    domain: values.domain,
    mailProvider: values.mailProvider,
    mailbox: values.email,
    auditAlias: values.audit,
    helloAlias: values.hello,
    domainPurchased: true,
    mailboxCreated: true,
    githubPagesAConfigured: Boolean(existing.githubPagesAConfigured),
    githubPagesWwwConfigured: Boolean(existing.githubPagesWwwConfigured),
    mxConfigured: Boolean(existing.mxConfigured),
    spfConfigured: Boolean(existing.spfConfigured),
    dkimConfigured: Boolean(existing.dkimConfigured),
    dmarcConfigured: Boolean(existing.dmarcConfigured),
    stripeQuickAuditLink: existing.stripeQuickAuditLink || "",
    stripeLaunchAuditLink: existing.stripeLaunchAuditLink || "",
    stripeEnterpriseReadinessLink: existing.stripeEnterpriseReadinessLink || "",
    stripeLinkFormatVerified: Boolean(existing.stripeLinkFormatVerified),
    stripeCheckoutQaConfirmed: Boolean(existing.stripeCheckoutQaConfirmed),
    stripeLinksVerified: Boolean(existing.stripeLinksVerified),
    founderReturnPacketApproved: Boolean(existing.founderReturnPacketApproved),
    domainMailboxPacketApproved: true,
    domainMailboxValuesApplied: values.apply,
    landingLinksApplied: Boolean(existing.landingLinksApplied),
    stagedRouteApprovalCount: Number(existing.stagedRouteApprovalCount || 0),
    firstTenRoutePacketApproved: Boolean(existing.firstTenRoutePacketApproved),
    stagedNamedRecipientApprovalCount: Number(existing.stagedNamedRecipientApprovalCount || 0),
    firstTenNamedRecipientPacketApproved: Boolean(existing.firstTenNamedRecipientPacketApproved),
    notes: [
      "Generated by scripts/apply-domain-mailbox-return-packet.mjs from a founder-approved domain and mailbox packet.",
      "Stripe remains pending until live Payment Links and checkout QA are approved.",
      "Run npm run launch:verify-dns before marking DNS records true.",
      "Do not mark firstTenRoutePacketApproved or firstTenNamedRecipientPacketApproved true until exact route or named-recipient message blocks are approved in the same turn."
    ]
  };

  fs.writeFileSync(file, `${JSON.stringify(status, null, 2)}\n`);
}

const args = parseArgs(process.argv.slice(2));
const input = readInput(args.file);
const dryRun = args["dry-run"] === "true";
const apply = args.apply === "true";

if (!input.includes("I approve applying these exact MCPScan domain and mailbox values")) {
  throw new Error("Domain and mailbox approval phrase is missing.");
}

if (!input.includes("Apply these domain and mailbox values before Stripe links exist")) {
  throw new Error("Approved pre-Stripe action phrase is missing.");
}

const domain = requireMatch("domain", input, /^Domain:\s*(.+)$/m).toLowerCase();
const mailProvider = requireMatch("mail provider", input, /^Mail provider:\s*(.+)$/m).toLowerCase();
const email = requireMatch("primary mailbox", input, /^Primary mailbox:\s*(.+)$/m).toLowerCase();
const audit = requireMatch("audit alias", input, /^Audit alias:\s*(.+)$/m).toLowerCase();
const hello = requireMatch("hello alias", input, /^Hello alias:\s*(.+)$/m).toLowerCase();

assertValid("domain", domain, validDomain);
assertValid("mail provider", mailProvider, validMailProvider);
assertValid("primary mailbox", email, validEmail);
assertValid("audit alias", audit, validEmail);
assertValid("hello alias", hello, validEmail);

for (const [label, value] of Object.entries({ email, audit, hello })) {
  if (!value.endsWith(`@${domain}`)) {
    throw new Error(`${label} must use the approved domain: ${domain}`);
  }
}

if (dryRun) {
  console.log("Domain and mailbox return packet dry run passed.");
  console.log(`Domain: ${domain}`);
  console.log(`Mail provider: ${mailProvider}`);
  console.log(`Security mailbox: ${email}`);
  console.log(`Audit alias: ${audit}`);
  console.log(`Hello alias: ${hello}`);
  process.exit(0);
}

if (apply) {
  const child = spawnSync(
    process.execPath,
    [
      "scripts/apply-domain-mailbox-launch-values.mjs",
      "--domain",
      domain,
      "--email",
      email
    ],
    { stdio: "inherit" }
  );

  if (child.status !== 0) {
    process.exit(child.status ?? 1);
  }
}

writeApprovalStatus({ domain, mailProvider, email, audit, hello, apply });

console.log("Parsed domain and mailbox return packet.");
console.log(`Mail provider: ${mailProvider}`);
console.log(`Security mailbox: ${email}`);
console.log(`Audit alias: ${audit}`);
console.log(`Hello alias: ${hello}`);
console.log("Wrote ops/founder-approval-status.json with Stripe pending.");
