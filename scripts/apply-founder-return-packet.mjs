#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

function parseArgs(argv) {
  const values = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (!arg.startsWith("--")) continue;
    const key = arg.slice(2);
    const next = argv[index + 1];
    if (!next || next.startsWith("--")) {
      values[key] = "true";
    } else {
      values[key] = next;
      index += 1;
    }
  }
  return values;
}

function readInput(file) {
  if (file) return fs.readFileSync(file, "utf8");
  return fs.readFileSync(0, "utf8");
}

function requireMatch(label, text, pattern) {
  const match = text.match(pattern);
  if (!match?.[1]) {
    throw new Error(`Missing ${label} in founder return packet.`);
  }
  return match[1].trim();
}

function validDomain(value) {
  return /^[a-z0-9.-]+\.[a-z]{2,}$/i.test(value);
}

function validEmail(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);
}

function validStripeUrl(value) {
  return /^https:\/\/buy\.stripe\.com\/\S+$/i.test(value) && !/test_/i.test(value);
}

function assertValid(label, value, test) {
  if (!test(value)) throw new Error(`Invalid ${label}: ${value}`);
}

function writeApprovalStatus(values) {
  const status = {
    generatedFor: "MCPScan first revenue launch",
    updatedAt: new Date().toISOString(),
    domain: values.domain,
    mailbox: values.email,
    auditAlias: values.audit,
    helloAlias: values.hello,
    domainPurchased: true,
    mailboxCreated: true,
    githubPagesAConfigured: false,
    githubPagesWwwConfigured: false,
    mxConfigured: false,
    spfConfigured: false,
    dkimConfigured: false,
    dmarcConfigured: false,
    stripeQuickAuditLink: values.quick,
    stripeLaunchAuditLink: values.launch,
    stripeEnterpriseReadinessLink: values.enterprise,
    stripeLinkFormatVerified: false,
    stripeCheckoutQaConfirmed: false,
    stripeLinksVerified: false,
    founderReturnPacketApproved: true,
    landingLinksApplied: true,
    stagedRouteApprovalCount: 0,
    firstTenRoutePacketApproved: false,
    stagedNamedRecipientApprovalCount: 0,
    firstTenNamedRecipientPacketApproved: false,
    notes: [
      "Generated by scripts/apply-founder-return-packet.mjs from a founder-approved return packet.",
      "Run npm run launch:verify-stripe and npm run launch:verify-stripe-qa before marking stripeLinksVerified true.",
      "Run npm run launch:verify-dns before marking DNS records true.",
      "Do not mark firstTenRoutePacketApproved or firstTenNamedRecipientPacketApproved true until exact route or named-recipient message blocks are approved in the same turn."
    ]
  };

  fs.writeFileSync(path.join(process.cwd(), "ops/founder-approval-status.json"), `${JSON.stringify(status, null, 2)}\n`);
}

const args = parseArgs(process.argv.slice(2));
const input = readInput(args.file);
const dryRun = args["dry-run"] === "true";

if (!input.includes("I approve applying these exact MCPScan launch values")) {
  throw new Error("Founder approval phrase is missing.");
}

if (!input.includes("Apply these links to the public landing page")) {
  throw new Error("Approved action phrase is missing.");
}

const domain = requireMatch("domain", input, /^Domain:\s*(.+)$/m).toLowerCase();
const email = requireMatch("primary mailbox", input, /^Primary mailbox:\s*(.+)$/m);
const audit = requireMatch("audit alias", input, /^Audit alias:\s*(.+)$/m);
const hello = requireMatch("hello alias", input, /^Hello alias:\s*(.+)$/m);
const quick = requireMatch("Quick Audit link", input, /^Quick Audit:\s*(.+)$/m);
const launch = requireMatch("Launch Audit link", input, /^Launch Audit:\s*(.+)$/m);
const enterprise = requireMatch("Enterprise Readiness link", input, /^Enterprise Readiness:\s*(.+)$/m);

assertValid("domain", domain, validDomain);
assertValid("primary mailbox", email, validEmail);
assertValid("audit alias", audit, validEmail);
assertValid("hello alias", hello, validEmail);
assertValid("Quick Audit link", quick, validStripeUrl);
assertValid("Launch Audit link", launch, validStripeUrl);
assertValid("Enterprise Readiness link", enterprise, validStripeUrl);

const uniqueStripeLinks = new Set([quick, launch, enterprise].map((value) => value.toLowerCase()));
if (uniqueStripeLinks.size !== 3) {
  throw new Error("Stripe Payment Links must be three unique URLs.");
}

for (const [label, value] of Object.entries({ email, audit, hello })) {
  if (!value.toLowerCase().endsWith(`@${domain}`)) {
    throw new Error(`${label} must use the approved domain: ${domain}`);
  }
}

if (dryRun) {
  console.log("Founder return packet dry run passed.");
  console.log(`Domain: ${domain}`);
  console.log(`Security mailbox: ${email}`);
  console.log(`Audit alias: ${audit}`);
  console.log(`Hello alias: ${hello}`);
  console.log("Stripe Payment Link values parsed and validated.");
  process.exit(0);
}

const child = spawnSync(
  process.execPath,
  [
    "scripts/apply-approved-launch-links.mjs",
    "--domain",
    domain,
    "--email",
    email,
    "--quick",
    quick,
    "--launch",
    launch,
    "--enterprise",
    enterprise
  ],
  { stdio: "inherit" }
);

if (child.status !== 0) {
  process.exit(child.status ?? 1);
}

writeApprovalStatus({ domain, email, audit, hello, quick, launch, enterprise });

console.log("Parsed founder return packet.");
console.log(`Security mailbox: ${email}`);
console.log(`Audit alias: ${audit}`);
console.log(`Hello alias: ${hello}`);
console.log("Wrote ops/founder-approval-status.json.");
